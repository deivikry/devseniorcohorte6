# Operadores de comparación o relacionales
a = 5
b = 3
print(a > b)
print(a < b)
print(a >= b)
print("a <= b, a es menor o igual que b:", a <= b)
print(a <= b)
print("a >= b, a es mayor o igual que b:", a >= b)
print(a == b)
print("a == b, a es diferente de b:", a != b)
print(a != b)
print("a != b, a es diferente de b:", a != b)